// العنوان يُقاس بنقاط الترميز بعد حذف التشكيل (U+064B–U+065F وU+0670): علامات التشكيل
// لا تزيد عرض السطر في نتيجة البحث فلا تُحسب. والوصف يُقاس بنقاط الترميز كما هو.

/** يحذف علامات التشكيل العربية (الفتحة…السكون والخنجرية). */
export const stripMarks = (s) => String(s).replace(/[ً-ٰٟ]/g, '');

/** طول العنوان بنقاط الترميز بعد حذف التشكيل. */
export const titleLen = (s) => [...stripMarks(s)].length;

/** طول الوصف بنقاط الترميز. */
export const descLen = (s) => [...String(s)].length;

/** حدود الرأس (العنوان = نواته قبل اسم العلامة). */
export const SEO_LIMITS = { titleMax: 60, titleMin: 30, descMax: 160, descMin: 110 };
